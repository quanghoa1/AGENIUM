#!/usr/bin/env bash
# Keep vendor/codex-sandbox in step with OpenAI Codex (see docs/reference/SANDBOX-MAINTENANCE.md).
#
#   devtools/scripts/sync-codex-sandbox.sh --check              offline: vendored files still match FILES.lock (CI)
#   devtools/scripts/sync-codex-sandbox.sh <ref> --summary      same / changed / missing-upstream per file vs <ref>
#   devtools/scripts/sync-codex-sandbox.sh <ref>                full unified diff vs <ref>
#   devtools/scripts/sync-codex-sandbox.sh <ref> --update       replace the vendored files with <ref>, rewrite FILES.lock + VENDOR.md
#
# <ref> is a commit sha, tag or branch of https://github.com/openai/codex. Files under upstream/ are never edited by hand.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
VDIR="$ROOT/vendor/codex-sandbox"
UP="$VDIR/upstream"
LOCK="$VDIR/FILES.lock"
REPO="openai/codex"

sha() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }
files() { grep -v '^\s*#' "$VDIR/FILES.txt" | sed '/^\s*$/d' | tr -d '\r'; }

if [ "${1:-}" = "--check" ]; then
  [ -f "$LOCK" ] || { echo "no FILES.lock: run devtools/scripts/sync-codex-sandbox.sh <ref> --update"; exit 1; }
  bad=0
  while read -r path hash; do
    [ -z "$path" ] && continue
    f="$UP/$path"
    if [ ! -f "$f" ]; then echo "MISSING  $path"; bad=1; continue; fi
    if [ "$(sha "$f")" != "$hash" ]; then echo "MODIFIED $path (vendored files must stay byte-for-byte upstream)"; bad=1; fi
  done < <(grep -v '^#' "$LOCK" | tr -d '\r')
  for path in $(files); do
    grep -q "^$path " "$LOCK" || { echo "UNLOCKED $path (listed in FILES.txt, run --update)"; bad=1; }
  done
  [ $bad -eq 0 ] && echo "vendor/codex-sandbox: $(grep -vc '^#' "$LOCK") files match FILES.lock"
  exit $bad
fi

REF="${1:?usage: sync-codex-sandbox.sh <ref> [--summary|--update] | --check}"
MODE="${2:-diff}"
META="$(curl -fsSL -H 'User-Agent: agenium-sync' "https://api.github.com/repos/$REPO/commits/$REF" || true)"
SHA="$(printf '%s' "$META" | grep -o '"sha": *"[0-9a-f]\{40\}"' | head -1 | grep -o '[0-9a-f]\{40\}' || true)"
# The API allows 60 calls an hour without a token: a tag or branch is then read with git, a sha taken as given.
if [ -z "$SHA" ]; then
  if [[ "$REF" =~ ^[0-9a-f]{40}$ ]]; then SHA="$REF"
  else SHA="$(git ls-remote "https://github.com/$REPO" "refs/tags/$REF^{}" "refs/heads/$REF" | head -1 | cut -f1)"; fi
fi
[ -n "$SHA" ] || { echo "cannot resolve $REF on $REPO" >&2; exit 2; }
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
echo "upstream $REPO @ $SHA"

for path in $(files); do
  mkdir -p "$TMP/$(dirname "$path")"
  if ! curl -fsSL "https://raw.githubusercontent.com/$REPO/$SHA/$path" -o "$TMP/$path"; then
    echo "missing-upstream  $path"; rm -f "$TMP/$path"; continue
  fi
  if [ ! -f "$UP/$path" ]; then echo "new               $path"
  elif cmp -s "$UP/$path" "$TMP/$path"; then [ "$MODE" = "--update" ] || echo "same              $path"
  else
    echo "changed           $path"
    [ "$MODE" = "diff" ] && diff -u "$UP/$path" "$TMP/$path" --label "vendored/$path" --label "$SHA/$path" || true
  fi
done

if [ "$MODE" = "--update" ]; then
  for path in $(files); do
    [ -f "$TMP/$path" ] || continue
    mkdir -p "$UP/$(dirname "$path")"
    cp "$TMP/$path" "$UP/$path"
  done
  {
    echo "# path sha256 — generated by devtools/scripts/sync-codex-sandbox.sh --update; do not edit"
    for path in $(files); do [ -f "$UP/$path" ] && echo "$path $(sha "$UP/$path")"; done
  } > "$LOCK"
  DATE="$(printf '%s' "$META" | grep -o '"date": *"[^"]*"' | sed -n '2p' | grep -o '[0-9T:Z-]\{20\}' || true)"
  DATE="${DATE:-read $(date -u +%F)}"
  sed -i.bak -e "s|^- Upstream commit: .*|- Upstream commit: \`$SHA\` ($DATE)|" "$VDIR/VENDOR.md" && rm -f "$VDIR/VENDOR.md.bak"
  echo "updated vendor/codex-sandbox to $SHA; review the derived code listed in VENDOR.md, then commit vendor/ alone"
fi
